class TestCandidateDepth:
    """component_top_k controls the real fusion candidate pool.

    Real BM25 component: on this corpus the query "match" ranks
    d-1 > d-2 > d-3 > d-rel (BM25 score>0 policy drops "d-x").
    """

    _DOCS = (
        ("d-1", "match match match match"),
        ("d-2", "match match match"),
        ("d-3", "match match"),
        ("d-rel", "match"),
        ("d-x", "unrelated"),
    )

    def test_bm25_baseline_ranking_for_fixture(self):
        corpus = _corpus(*self._DOCS)
        result = BM25Retriever().retrieve("match", corpus, top_k=5)
        assert result.document_ids == ("d-1", "d-2", "d-3", "d-rel")

    def test_shallow_depth_excludes_relevant_candidate(self):
        corpus = _corpus(*self._DOCS)
        dense = _stub(DENSE_ID)
        retriever = _hybrid(
            sparse=BM25Retriever(), dense=dense, component_top_k=3
        )
        result = retriever.retrieve("match", corpus, top_k=3)
        assert result.document_ids == ("d-1", "d-2", "d-3")
        assert "d-rel" not in result.document_ids
        assert dense.calls[0]["top_k"] == 3

    def test_deeper_depth_admits_relevant_candidate(self):
        corpus = _corpus(*self._DOCS)
        dense = _stub(DENSE_ID)
        retriever = _hybrid(
            sparse=BM25Retriever(), dense=dense, component_top_k=5
        )
