    def test_metrics_consume_fused_ranking_only(self):
        # d-rel is relevant and present in the sparse component ranking
        # but falls outside the fused top_k. If the evaluator ever saw
        # component rankings as extra events, recall would wrongly be
        # non-zero / no RETRIEVAL_MISS.
        sparse = _stub(SPARSE_ID, "d-s1", "d-s2", "d-rel")
        dense = _stub(DENSE_ID, "d-d1", "d-d2", "d-d3")
