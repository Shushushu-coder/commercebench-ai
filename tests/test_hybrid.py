def _corpus(*documents: tuple) -> Corpus:
    return Corpus(
        corpus_id="c",
        corpus_version="1",
        documents=tuple(
            Document(document_id=document_id, text=text)
            for document_id, text in documents
        ),
    )


class StubRetriever:
    """Deterministic Retriever: fixed ranking that honors top_k."""

    retriever_version = "0.1"

    def __init__(self, retriever_id, document_ids, scores=None):
        self.retriever_id = retriever_id
        self._document_ids = tuple(document_ids)
        self._scores = (
            tuple(scores)
            if scores is not None
            else tuple(
                float(len(document_ids) - i)
                for i in range(len(document_ids))
            )
        )
        self.calls = []

    def retrieve(self, query, corpus, top_k):
        self.calls.append(
            {"query": query, "corpus": corpus, "top_k": top_k}
        )
        document_ids = self._document_ids[:top_k]
        return RetrievalResult(
            query=query,
            document_ids=document_ids,
            scores=self._scores[: len(document_ids)],
        )


def _stub(retriever_id, *document_ids, **kwargs):
    return StubRetriever(retriever_id, document_ids, **kwargs)


def _hybrid(sparse=None, dense=None, **kwargs) -> HybridRRFRetriever:
    """HybridRRFRetriever wired to stub components by retriever_id."""
    components = {
        SPARSE_ID: (
            sparse if sparse is not None else _stub(SPARSE_ID)
        ),
        DENSE_ID: dense if dense is not None else _stub(DENSE_ID),
    }
    return HybridRRFRetriever(
        sparse=copy.deepcopy(SPARSE_CONFIG),
        dense=copy.deepcopy(DENSE_CONFIG),
        component_factory=lambda config: components[config.retriever_id],
        **kwargs,
    )


