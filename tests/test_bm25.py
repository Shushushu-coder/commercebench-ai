"""Tests for the Phase 1C Okapi BM25 retriever and parameter plumbing.

All expected score literals below are hand-computed from the frozen
``bm25-okapi-v0`` formula::

    score(D, Q) = Σ IDF(q) * f(q,D)(k1+1) / (f(q,D) + k1(1-b+b|D|/avgdl))
    IDF(q) = ln(1 + (N - n(q) + 0.5) / (n(q) + 0.5))

with k1 = 1.5 and b = 0.75 unless a test says otherwise. They are not
generated by calling any production helper.
"""

