def _corpus(*documents: tuple) -> Corpus:
    return Corpus(
        corpus_id="c",
        corpus_version="1",
        documents=tuple(
            Document(document_id=document_id, text=text)
            for document_id, text in documents
        ),
    )


@pytest.fixture
def shoe_corpus() -> Corpus:
    # d1: tokens = [red, shoe, shoe] (|D|=3); d2: [red, bag] (|D|=2).
    # N=2, avgdl=2.5. df(shoe)=1 -> idf=ln(2); df(red)=2 -> idf=ln(1.2).
    return _corpus(
        ("d1", "red shoe shoe"),
        ("d2", "red bag"),
    )


