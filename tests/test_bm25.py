class TestExactScores:
    def test_single_term_exact_score(self, shoe_corpus):
        # N=2, avgdl=2.5, df(shoe)=1 -> idf=ln(2)=0.6931471805599453.
        # d1: f=2, |D|=3 -> ln(2) * 2*2.5 / (2 + 1.5*(0.25 + 0.75*3/2.5))
        #                  = ln(2) * 5 / 3.725.
        result = BM25Retriever().retrieve("shoe", shoe_corpus, top_k=3)
        assert result.document_ids == ("d1",)
        assert result.scores == pytest.approx((0.9303989000804636,))

    def test_multi_term_exact_score_is_summed(self, shoe_corpus):
        # query "shoe red": df(red)=2 -> idf=ln(1.2)=0.1823215567939546.
        # d1 red contribution = ln(1.2) * 2.5 / (1 + 1.5*1.15) = 0.167267...
        # d2 has only "red": ln(1.2) * 2.5 / (1 + 1.5*0.85) = 0.200353...
        result = BM25Retriever().retrieve("shoe red", shoe_corpus, top_k=3)
        assert result.document_ids == ("d1", "d2")
        assert result.scores == pytest.approx(
            (1.0976663833776696, 0.20035335911423582)
        )
        # The d1 score is exactly the sum of its two term contributions.
        assert result.scores[0] == pytest.approx(
            0.9303989000804636 + 0.16726748329720606
        )

    def test_duplicate_document_term_frequency_counted(self):
        # d1 has "match" twice: its tf contribution must use f=2, not 1.
        corpus = _corpus(
            ("d1", "match match alpha"),
            ("d2", "match beta gamma"),
        )
        result = BM25Retriever().retrieve("match", corpus, top_k=2)
        assert result.document_ids == ("d1", "d2")
        assert result.scores[0] > result.scores[1]

    def test_document_length_normalization(self):
        # Same tf for "match"; the longer document must score lower.
        # N=2, avgdl=5, df(match)=2 -> idf=ln(1.2).
        corpus = _corpus(
            ("short", "match alpha"),
            ("long", "match beta beta beta beta beta beta beta"),
        )
        result = BM25Retriever().retrieve("match", corpus, top_k=2)
        assert result.document_ids == ("short", "long")
        assert result.scores == pytest.approx(
            (0.24975555725199255, 0.14356028094012174)
        )

    def test_tf_saturation_is_sublinear(self):
        # Same document length, tf 1 vs 2: raw term-frequency ratio is
        # exactly 2.0; BM25 saturates to 5/3.5 / (2.5/2.5) = 1.4286.
        corpus = _corpus(
            ("d-a", "match alpha beta"),
            ("d-b", "match match beta"),
        )
        result = BM25Retriever().retrieve("match", corpus, top_k=2)
        assert result.document_ids == ("d-b", "d-a")
        assert result.scores == pytest.approx(
            (0.26045936684850657, 0.1823215567939546)
        )
        assert result.scores[0] / result.scores[1] < 2.0
        tf_scores = TermFrequencyRetriever().retrieve(
            "match", corpus, top_k=2
        ).scores
        assert tf_scores == (2.0, 1.0)
        assert tf_scores[0] / tf_scores[1] == 2.0


class TestRankingSemanticsAndEdges:
    def test_stable_tie_break_by_document_id(self):
        corpus = _corpus(
            ("z-doc", "target term"),
            ("a-doc", "target term"),
        )
        result = BM25Retriever().retrieve("target", corpus, top_k=2)
        assert result.document_ids == ("a-doc", "z-doc")
        assert result.scores[0] == pytest.approx(result.scores[1])

    def test_top_k_limits_results(self, shoe_corpus):
        result = BM25Retriever().retrieve("shoe red", shoe_corpus, top_k=1)
        assert result.document_ids == ("d1",)
        assert len(result.scores) == 1

    def test_zero_score_documents_filtered(self, shoe_corpus):
        corpus = _corpus(
            ("d1", "red shoe shoe"),
            ("d2", "red bag"),
            ("d3", "completely unrelated text"),
        )
        result = BM25Retriever().retrieve("shoe", corpus, top_k=3)
        assert "d3" not in result.document_ids
        assert all(score > 0 for score in result.scores)

    def test_query_without_tokens_returns_empty(self, shoe_corpus):
        result = BM25Retriever().retrieve("!!!", shoe_corpus, top_k=3)
        assert result.document_ids == ()
        assert result.scores == ()
        assert result.query == "!!!"

    def test_no_match_returns_empty(self, shoe_corpus):
        result = BM25Retriever().retrieve("zzz", shoe_corpus, top_k=3)
        assert result.document_ids == ()

    def test_empty_corpus_returns_empty(self):
        corpus = Corpus(corpus_id="c", corpus_version="1", documents=())
        result = BM25Retriever().retrieve("shoe", corpus, top_k=3)
        assert result.document_ids == ()
        assert result.scores == ()

    def test_tokenless_document_ignored_safely(self):
        corpus = _corpus(
            ("tokenless", "!!! ???"),
            ("real", "match here"),
        )
        result = BM25Retriever().retrieve("match", corpus, top_k=2)
        assert result.document_ids == ("real",)

    def test_all_documents_tokenless_no_division_by_zero(self):
        # Every document tokenizes to empty -> avgdl == 0 -> stable empty.
        corpus = _corpus(("a", "!!!"), ("b", "???"))
        result = BM25Retriever().retrieve("match", corpus, top_k=2)
        assert result.document_ids == ()
        assert result.scores == ()

    def test_scores_aligned_and_descending(self, shoe_corpus):
        result = BM25Retriever().retrieve("shoe red", shoe_corpus, top_k=3)
        assert len(result.document_ids) == len(result.scores)
        assert list(result.scores) == sorted(result.scores, reverse=True)

    def test_protocol_and_identity(self):
        retriever = BM25Retriever()
        assert isinstance(retriever, Retriever)
        assert retriever.retriever_id == "bm25-okapi-v0"
        assert retriever.retriever_version == "0.1"

    def test_deterministic_repeated_runs(self, shoe_corpus):
        retriever = BM25Retriever()
        first = retriever.retrieve("shoe red", shoe_corpus, top_k=3)
        second = retriever.retrieve("shoe red", shoe_corpus, top_k=3)
        assert first == second


class TestBuildRetrieverPlumbing:
    def test_build_bm25_with_defaults(self):
        retriever = build_retriever(
            RetrievalConfig(retriever_id="bm25-okapi-v0")
        )
        assert isinstance(retriever, BM25Retriever)
        assert retriever.k1 == 1.5
        assert retriever.b == 0.75

    def test_build_bm25_with_custom_parameters(self):
        retriever = build_retriever(
            RetrievalConfig(
                retriever_id="bm25-okapi-v0",
                parameters={"k1": 1.2, "b": 0.5},
            )
        )
        assert retriever.k1 == 1.2
        assert retriever.b == 0.5

    def test_pipeline_parameters_not_passed_to_retriever(self):
        # top_k / corpus_id / corpus_version are pipeline-level keys owned
        # by the system layer; they must not be treated as unknown
        # algorithm parameters nor passed into BM25Retriever.__init__.
        retriever = build_retriever(
            RetrievalConfig(
                retriever_id="bm25-okapi-v0",
                parameters={
                    "top_k": 3,
                    "corpus_id": "c",
                    "corpus_version": "1",
                },
            )
        )
        assert isinstance(retriever, BM25Retriever)
        assert retriever.k1 == 1.5
        assert retriever.b == 0.75

    @pytest.mark.parametrize(
        "parameters",
        [
            {"k11": 1.5},
            {"k1": 1.5, "typo_param": 2},
            {"bb": 0.75},
        ],
    )
    def test_unknown_algorithm_parameter_rejected(self, parameters):
        with pytest.raises(ContractValidationError, match="algorithm"):
            build_retriever(
                RetrievalConfig(
                    retriever_id="bm25-okapi-v0", parameters=parameters
                )
            )

    @pytest.mark.parametrize(
        "parameters",
        [{"k1": 0}, {"b": 1.5}, {"k1": True}, {"k1": float("nan")}],
    )
    def test_invalid_parameter_values_rejected_via_factory(self, parameters):
        with pytest.raises(ContractValidationError):
            build_retriever(
                RetrievalConfig(
                    retriever_id="bm25-okapi-v0", parameters=parameters
                )
            )

    def test_parameterless_baselines_reject_algorithm_keys(self):
        # keyword-match-v0 and term-frequency-v0 declare no algorithm
        # parameters: a stray "k1" must not be silently ignored there
        # either.
        for retriever_id in ("keyword-match-v0", "term-frequency-v0"):
            with pytest.raises(ContractValidationError, match="algorithm"):
                build_retriever(
                    RetrievalConfig(
                        retriever_id=retriever_id, parameters={"k1": 1.5}
                    )
                )

    def test_existing_baselines_unchanged_through_factory(self):
        mini = _corpus(
            ("d-a", "alpha beta beta gamma"),
            ("d-b", "alpha beta"),
            ("d-c", "unrelated words"),
        )
        pipeline_params = {
            "top_k": 3,
            "corpus_id": "c",
            "corpus_version": "1",
        }
        keyword = build_retriever(
            RetrievalConfig(
                retriever_id="keyword-match-v0", parameters=pipeline_params
            )
        )
        term_frequency = build_retriever(
            RetrievalConfig(
                retriever_id="term-frequency-v0", parameters=pipeline_params
            )
        )
        assert isinstance(keyword, KeywordMatchRetriever)
        assert isinstance(term_frequency, TermFrequencyRetriever)
        kw = keyword.retrieve("alpha beta", mini, top_k=3)
        tf = term_frequency.retrieve("beta", mini, top_k=3)
        assert kw.document_ids == ("d-a", "d-b")
        assert kw.scores == (2.0, 2.0)
        assert tf.document_ids == ("d-a", "d-b")
        assert tf.scores == (2.0, 1.0)

    def test_parameters_actually_affect_runtime_output(self):
        # If parameters reached only the fingerprint this test would fail:
        # different b values must produce different runtime scores.
        corpus = _corpus(
            ("short", "match alpha"),
            ("long", "match beta beta beta beta beta beta beta"),
        )
        scores_by_b = {}
        for b in (0.0, 0.75, 1.0):
            retriever = build_retriever(
                RetrievalConfig(
                    retriever_id="bm25-okapi-v0", parameters={"b": b}
                )
            )
            scores_by_b[b] = retriever.retrieve(
                "match", corpus, top_k=2
            ).scores
        assert scores_by_b[0.0] != scores_by_b[0.75] != scores_by_b[1.0]
        # b=0 disables length normalization: equal tf -> equal scores.
        assert scores_by_b[0.0][0] == pytest.approx(scores_by_b[0.0][1])

        scores_by_k1 = {}
        saturated = _corpus(
            ("d-a", "match alpha beta"),
            ("d-b", "match match beta"),
        )
        for k1 in (0.5, 1.5, 3.0):
            retriever = build_retriever(
                RetrievalConfig(
                    retriever_id="bm25-okapi-v0", parameters={"k1": k1}
                )
            )
            scores_by_k1[k1] = retriever.retrieve(
                "match", saturated, top_k=2
            ).scores
        assert (
            scores_by_k1[0.5] != scores_by_k1[1.5] != scores_by_k1[3.0]
        )


def _bm25_manifest(parameters: dict) -> ExperimentManifest:
    return ExperimentManifest(
        schema_version=SCHEMA_VERSION,
        experiment_id="exp",
        experiment_name="exp",
        benchmark_version="commercebench-dev-0.1",
        case_ids=("rag-coupon-001",),
        system_id="deterministic-rag",
        system_version="0.1",
        model=None,
        retrieval=RetrievalConfig(
            retriever_id="bm25-okapi-v0", parameters=parameters
        ),
        memory=None,
        evaluator_id="deterministic-rag-v0",
        evaluator_version="0.1",
        random_seed=0,
        metadata={},
    )


class TestParameterFingerprint:
    _BASE = {
        "top_k": 3,
        "corpus_id": "commercebench-dev-corpus",
        "corpus_version": "0.1",
        "k1": 1.5,
        "b": 0.75,
    }

    def test_same_config_same_fingerprint(self):
        first = _bm25_manifest(dict(self._BASE)).config_fingerprint()
        second = _bm25_manifest(dict(self._BASE)).config_fingerprint()
        assert first == second

    def test_k1_change_changes_fingerprint(self):
        changed = dict(self._BASE, k1=1.2)
        assert _bm25_manifest(self._BASE).config_fingerprint() != (
            _bm25_manifest(changed).config_fingerprint()
        )

    def test_b_change_changes_fingerprint(self):
        changed = dict(self._BASE, b=0.5)
        assert _bm25_manifest(self._BASE).config_fingerprint() != (
            _bm25_manifest(changed).config_fingerprint()
        )

    def test_top_k_change_changes_fingerprint(self):
        changed = dict(self._BASE, top_k=5)
        assert _bm25_manifest(self._BASE).config_fingerprint() != (
            _bm25_manifest(changed).config_fingerprint()
        )

    def test_fingerprinted_parameters_reach_runtime(
        self, rag_corpus, rag_cases
    ):
        # The same parameter that changes the fingerprint must also
        # change what the runtime retriever computes.
        case = rag_cases["rag-coupon-001"]
        default = build_retriever(
            _bm25_manifest(self._BASE).retrieval
        ).retrieve(case.user_input, rag_corpus, top_k=3)
        altered = build_retriever(
            _bm25_manifest(dict(self._BASE, k1=0.2)).retrieval
        ).retrieve(case.user_input, rag_corpus, top_k=3)
        assert default.scores != altered.scores


