class TestControlledComparison:
    """term-frequency-v0 vs bm25-okapi-v0: same everything else."""

    def test_only_retrieval_configuration_differs(
        self, bm25_manifest, term_frequency_manifest
    ):
        for field in (
            "benchmark_version",
            "case_ids",
            "system_id",
            "system_version",
            "model",
            "memory",
            "evaluator_id",
            "evaluator_version",
            "random_seed",
        ):
            assert getattr(bm25_manifest, field) == getattr(
                term_frequency_manifest, field
            )
        assert (
            bm25_manifest.retrieval.retriever_id
            != term_frequency_manifest.retrieval.retriever_id
        )
        # BM25's k1/b are part of its algorithm definition; the changed
        # dimension is the retrieval strategy configuration as a whole.
        assert bm25_manifest.config_fingerprint() != (
            term_frequency_manifest.config_fingerprint()
        )

    def test_bm25_and_term_frequency_rankings_differ(
        self,
        bm25_manifest,
        term_frequency_manifest,
        rag_corpus,
        rag_cases,
        rag_answers,
    ):
        case = rag_cases["rag-coupon-001"]
        bm25_system = DeterministicRAGSystem.from_manifest(
            bm25_manifest, rag_corpus, rag_answers
        )
        tf_system = DeterministicRAGSystem.from_manifest(
            term_frequency_manifest, rag_corpus, rag_answers
        )
        bm25_ids = run_case(
            case, bm25_manifest, bm25_system
        ).retrieval_events[0].document_ids
        tf_ids = run_case(
            case, term_frequency_manifest, tf_system
        ).retrieval_events[0].document_ids
        # term-frequency ranks the repeated-"discount" distractor first;
        # BM25's IDF + length normalization restores policy-coupon-001.
        assert tf_ids == ("policy-promo-001", "policy-coupon-001")
        assert bm25_ids == ("policy-coupon-001", "policy-promo-001")
        assert bm25_ids != tf_ids

    def test_metric_difference_is_real(
        self,
        bm25_manifest,
        term_frequency_manifest,
        rag_corpus,
        rag_cases,
        rag_answers,
    ):
        case = rag_cases["rag-coupon-001"]
        evaluator = DeterministicRAGEvaluator(ks=(1, 3))
        bm25_system = DeterministicRAGSystem.from_manifest(
            bm25_manifest, rag_corpus, rag_answers
        )
        tf_system = DeterministicRAGSystem.from_manifest(
            term_frequency_manifest, rag_corpus, rag_answers
        )
        bm25_result = evaluator.evaluate(
            case, run_case(case, bm25_manifest, bm25_system)
        )
        tf_result = evaluator.evaluate(
            case, run_case(case, term_frequency_manifest, tf_system)
        )
        assert bm25_result.metrics["retrieval_recall_at_1"].value == 1.0
        assert tf_result.metrics["retrieval_recall_at_1"].value == 0.0
        assert bm25_result.metrics["retrieval_mrr"].value == 1.0
        assert tf_result.metrics["retrieval_mrr"].value == 0.5
        assert bm25_result.metrics["exact_match"].value is True
        assert tf_result.metrics["exact_match"].value is False
        assert bm25_result.passed is True
        assert tf_result.passed is False

    def test_length_normalization_flips_keyword_ordering(self):
        # Same keyword score (both match "aa" and "bb"); keyword falls
        # back to document_id order while BM25 prefers the shorter doc.
        corpus = _corpus(
            ("a-doc", "aa bb cc dd ee ff"),
            ("z-doc", "aa bb"),
        )
        keyword_ids = KeywordMatchRetriever().retrieve(
            "aa bb", corpus, top_k=2
        ).document_ids
        bm25_result = BM25Retriever().retrieve("aa bb", corpus, top_k=2)
        assert keyword_ids == ("a-doc", "z-doc")
        assert bm25_result.document_ids == ("z-doc", "a-doc")
        assert bm25_result.document_ids != keyword_ids
        assert bm25_result.scores == pytest.approx(
            (0.47050724333923766, 0.2976678478268646)
        )

    def test_bm25_vs_tf_difference_not_hardcoded(self):
        # Difference must come from the formula (tf saturation here),
        # not from a retriever_id special-case.
        corpus = _corpus(
            ("broad", "aa bb cc"),
            ("narrow", "aa aa aa aa"),
        )
        tf = TermFrequencyRetriever().retrieve("aa bb cc", corpus, top_k=2)
        bm25 = BM25Retriever().retrieve("aa bb cc", corpus, top_k=2)
        assert tf.document_ids == ("narrow", "broad")
        assert tf.scores == (4.0, 3.0)
        assert bm25.document_ids == ("broad", "narrow")
